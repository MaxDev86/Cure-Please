#!/usr/bin/env python3
"""Generates src/CurePlease/Core/ZoneNames.cs from Windower's res/zones.lua.

Usage: python tools/gen_zone_names.py [path-to-zones.lua]
Default source: D:/FFXI/Windower4/res/zones.lua
Output is written next to the CurePlease project; review before committing.
"""
import re
import sys

src = sys.argv[1] if len(sys.argv) > 1 else "D:/FFXI/Windower4/res/zones.lua"
out_path = "src/CurePlease/Core/ZoneNames.cs"

entry_re = re.compile(r'^\s*\[(\d+)\] = \{id=\d+,en="((?:[^"\\]|\\.)*)"')

entries = []
for line in open(src, encoding="utf-8"):
    m = entry_re.match(line)
    if m:
        entries.append((int(m.group(1)), m.group(2)))

out = []
out.append("// GENERATED by tools/gen_zone_names.py from Windower res/zones.lua - do not edit by hand.")
out.append("using System.Collections.Generic;")
out.append("")
out.append("namespace CurePlease.Core")
out.append("{")
out.append("    /// <summary>Zone id -> English zone name lookup (Windower zones.lua).</summary>")
out.append("    public static class ZoneNames")
out.append("    {")
out.append("        private static readonly IReadOnlyDictionary<int, string> Names =")
out.append("            new Dictionary<int, string>")
out.append("        {")
for zid, en in entries:
    out.append('            { %d, "%s" },' % (zid, en.replace('\\', '\\\\').replace('"', '\\"')))
out.append("        };")
out.append("")
out.append("        /// <summary>English zone name for a zone id; null when unknown.</summary>")
out.append("        /// <param name=\"zoneId\">Zone id from the client (Player.ZoneId).</param>")
out.append("        /// <returns>The zone name, or null when the id is not mapped.</returns>")
out.append("        public static string Name(int zoneId)")
out.append("        {")
out.append("            return Names.TryGetValue(zoneId, out string name) ? name : null;")
out.append("        }")
out.append("    }")
out.append("}")

with open(out_path, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(out) + "\n")

print("wrote %s (%d zones)" % (out_path, len(entries)))
