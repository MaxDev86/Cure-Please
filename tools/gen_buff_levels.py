#!/usr/bin/env python3
"""Generates CurePlease Core/BuffCatalogLevels.cs from Windower's spells.lua.

The Buff Upkeep job filter needs structured job->level data for the catalog's
spells. The spell list is scraped from Core/BuffCatalog.cs (the hand-curated
catalog), and levels come from spells.lua's levels={...} tables.

Usage: gen_buff_levels.py <path-to-spells.lua> <path-to-BuffCatalog.cs>
"""
import re, sys

lua_path, catalog_path = sys.argv[1], sys.argv[2]

catalog_src = open(catalog_path, encoding="utf-8").read()
wanted = []
for m in re.finditer(r'new BuffCatalogEntry\("([^"]+)"', catalog_src):
    if m.group(1) not in wanted:
        wanted.append(m.group(1))

lua_src = open(lua_path, encoding="utf-8").read()
entry_re = re.compile(
    r'\{\s*id=\d+,\s*en="(?P<en>[^"]+)",.*?levels=\{(?P<levels>[^}]*)\}',
    re.S)

levels_by_name = {}
for m in entry_re.finditer(lua_src):
    name = m.group("en")
    if name in levels_by_name:
        continue
    levels = {int(j): int(l) for j, l in re.findall(r"\[(\d+)\]=(\d+)", m.group("levels"))}
    # Keep raw levels: >99 marks JP-gated spells (100 = main-only II spells,
    # 1200 = 99 + spent-JP spells like Refresh III). The C# side interprets.
    levels = {j: l for j, l in levels.items() if 1 <= j <= 22}
    if levels:
        levels_by_name[name] = levels

missing = [s for s in wanted if s not in levels_by_name]

out = []
out.append("// GENERATED by tools/gen_buff_levels.py from Windower's res/spells.lua - do not edit by hand.")
out.append("// Job id -> level learned, for every BuffCatalog spell. Used by the Buff Upkeep job filter.")
out.append("using System;")
out.append("using System.Collections.Generic;")
out.append("")
out.append("namespace CurePlease.Core")
out.append("{")
out.append("    internal static class BuffCatalogLevels")
out.append("    {")
out.append("        public static readonly IReadOnlyDictionary<string, IReadOnlyDictionary<int, int>> Table =")
out.append("            new Dictionary<string, IReadOnlyDictionary<int, int>>(StringComparer.OrdinalIgnoreCase)")
out.append("            {")
for name in wanted:
    levels = levels_by_name.get(name)
    if not levels:
        continue
    pairs = ", ".join("{{ {}, {} }}".format(j, l) for j, l in sorted(levels.items()))
    out.append('                ["{}"] = new Dictionary<int, int> {{ {} }},'.format(name, pairs))
out.append("            };")
out.append("    }")
out.append("}")

print("\n".join(out))
print(file=sys.stderr)
if missing:
    print("WARNING: no level data found for: " + ", ".join(missing), file=sys.stderr)
