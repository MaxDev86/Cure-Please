#!/usr/bin/env python3
"""Generates CurePlease Core/AbilityCatalog.cs.

Client ability DATs carry no job/level data (unlike spell DATs), so job and
level come from LandSandBoat's curated table:
    https://raw.githubusercontent.com/LandSandBoat/server/base/sql/abilities.sql
English names and categories come from Windower's res/job_abilities.lua.

Excluded: monster abilities, pet commands, blood pacts (pet/avatar-gated, not
job-learned), wyvern breaths (LSB job 0), monstrosity (LSB job 23).

Usage: gen_ability_catalog.py <abilities.sql> <job_abilities.lua>
"""
import re, sys

sql_path, lua_path = sys.argv[1], sys.argv[2]

# Windower job_abilities.lua: one entry per line.
lua_names = {}
lua_types = {}
entry_re = re.compile(r'^\s*\[(\d+)\] = \{.*en="([^"]+)".*type="([^"]+)"')
for line in open(lua_path, encoding="utf-8"):
    m = entry_re.match(line)
    if m:
        lua_names[int(m.group(1))] = m.group(2)
        lua_types[int(m.group(1))] = m.group(3)

# Categories that are real job-learned abilities, mapped to display text.
INCLUDE_TYPES = {
    "JobAbility": "Ability",
    "Scholar": "Stratagem",
    "CorsairRoll": "Roll",
    "CorsairShot": "Shot",
    "Waltz": "Waltz",
    "Samba": "Samba",
    "Step": "Step",
    "Jig": "Jig",
    "Flourish1": "Flourish I",
    "Flourish2": "Flourish II",
    "Flourish3": "Flourish III",
    "Rune": "Rune",
    "Effusion": "Effusion",
    "Ward": "Ward",
}

insert_re = re.compile(r"INSERT INTO `abilities` VALUES \((.*)\);")
rows = []
skipped_type = 0
missing_lua = []
for line in open(sql_path, encoding="utf-8"):
    m = insert_re.match(line.strip())
    if not m:
        continue
    f = m.group(1).split(",")
    ability_id = int(f[0])
    job = int(f[2])
    level = int(f[3])
    add_type = int(f[19])  # LSB ADDTYPE: 1=merit, 2=astral flow, 4=main-only, 8=learned from item
    if not (1 <= job <= 22):
        continue  # wyvern breaths (0), monstrosity (23)
    wtype = lua_types.get(ability_id)
    if wtype not in INCLUDE_TYPES:
        skipped_type += 1
        continue
    if ability_id not in lua_names:
        missing_lua.append(ability_id)
        continue
    rows.append((ability_id, lua_names[ability_id], job, max(level, 1), add_type, INCLUDE_TYPES[wtype]))

rows.sort(key=lambda r: (r[2], r[3], r[1]))

entry_class = '''
    /// <summary>One job-ability learning entry: which job learns it, at what level, and how.</summary>
    public sealed class AbilityCatalogEntry
    {
        public AbilityCatalogEntry(int id, string name, int jobId, int level, int addTypeFlags, string type)
        {
            Id = id;
            Name = name;
            JobId = jobId;
            Level = level;
            AddTypeFlags = addTypeFlags;
            Type = type;
        }

        /// <summary>Ability id (Windower job_abilities.lua id; key for HasAbility).</summary>
        public int Id { get; }

        /// <summary>English ability name.</summary>
        public string Name { get; }

        /// <summary>Job id (1-22) that learns this ability.</summary>
        public int JobId { get; }

        /// <summary>Job level the ability is learned at; two-hours are stored as 1.</summary>
        public int Level { get; }

        /// <summary>Raw acquisition flags (LSB ADDTYPE): 1 merit, 4 main-only, 8 item-learned.</summary>
        public int AddTypeFlags { get; }

        /// <summary>True when the ability requires merit point allocation (e.g. Altruism).</summary>
        public bool MeritGated => (AddTypeFlags & 1) != 0;

        /// <summary>True when usable only as main job (e.g. Afflatus Solace, Composure).</summary>
        public bool MainOnly => (AddTypeFlags & 4) != 0;

        /// <summary>True when learned from an item instead of leveling (e.g. COR rolls from dice).</summary>
        public bool ItemLearned => (AddTypeFlags & 8) != 0;

        /// <summary>Display category: Ability, Stratagem, Roll, Waltz, Step, ...</summary>
        public string Type { get; }
    }
'''

out = []
out.append("// GENERATED by tools/gen_ability_catalog.py - do not edit by hand.")
out.append("// Job/level: LandSandBoat sql/abilities.sql (client ability DATs carry none).")
out.append("// Names/categories: Windower res/job_abilities.lua. Level 0 (two-hours) stored as 1.")
out.append("using System.Collections.Generic;")
out.append("using System.Linq;")
out.append("")
out.append("namespace CurePlease.Core")
out.append("{")
out.append(entry_class)
out.append("    /// <summary>Curated per-job ability learning data for the Character Info abilities tab.</summary>")
out.append("    public static class AbilityCatalog")
out.append("    {")
out.append("        public static readonly IReadOnlyList<AbilityCatalogEntry> All = new List<AbilityCatalogEntry>")
out.append("        {")
for ability_id, name, job, level, add_type, dtype in rows:
    out.append('            new AbilityCatalogEntry({}, "{}", {}, {}, {}, "{}"),'.format(
        ability_id, name.replace('"', '\\"'), job, level, add_type, dtype))
out.append("        };")
out.append("")
out.append("        /// <summary>All catalog entries for one job, ordered by level then name.</summary>")
out.append("        /// <param name=\"jobId\">Job id (1-22).</param>")
out.append("        /// <returns>Entries learned by that job.</returns>")
out.append("        public static IEnumerable<AbilityCatalogEntry> ForJob(int jobId)")
out.append("        {")
out.append("            return All.Where(e => e.JobId == jobId).OrderBy(e => e.Level).ThenBy(e => e.Name);")
out.append("        }")
out.append("    }")
out.append("}")

print("\n".join(out))
print(file=sys.stderr)
print("entries: {} (skipped by type: {})".format(len(rows), skipped_type), file=sys.stderr)
if missing_lua:
    print("WARNING: no job_abilities.lua entry for ids: " + ", ".join(map(str, missing_lua)), file=sys.stderr)
